import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
await build({
  entryPoints: [root+'plugins/openrevive/mcp/src/server.mjs'],
  absWorkingDir: root,
  outfile: root+'plugins/openrevive/mcp/server.mjs',
  bundle: true, platform: 'node', target: 'node20', format: 'esm',
  nodePaths: [root+'tools/mcp/node_modules'], legalComments: 'eof',
  banner: {js: '// Generated by tools/mcp/build.mjs. Edit mcp/src/server.mjs, then rebuild.'},
});
let licenses = 'Bundled runtime dependencies (build-only dependencies are not distributed).\n';
for (const name of ['@modelcontextprotocol/server', '@modelcontextprotocol/core', 'zod']) {
  const dir = root+'tools/mcp/node_modules/'+name+'/';
  const pkg = JSON.parse(await readFile(dir+'package.json', 'utf8'));
  licenses += '\n===== '+name+' '+pkg.version+' ('+pkg.license+') =====\n'+await readFile(dir+'LICENSE', 'utf8');
}
await writeFile(root+'plugins/openrevive/mcp/THIRD_PARTY_LICENSES.txt', licenses);
console.error('OPENREVIVE_MCP_BUILD_OK');
